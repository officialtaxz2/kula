#!/usr/bin/env bash
# Idempotent Kula deployment and one-time protected Caddy integration.
# Run: sudo bash deploy/setup.sh
set -Eeuo pipefail
umask 022

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CADDYFILE="${CADDYFILE:-/etc/caddy/Caddyfile}"
SITEFILE="$(dirname "$CADDYFILE")/kula-monitor.caddy"
IMPORT_LINE="import ${SITEFILE}"
KULA_LOCAL_URL="http://127.0.0.1:27960/health"
CONTAINER="kula-monitor"

error() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '\n==> %s\n' "$*"; }
compose() { docker compose -f "$ROOT_DIR/compose.yaml" "$@"; }
container_running() { [[ "$(docker inspect -f '{{.State.Running}}' "$CONTAINER" 2>/dev/null || true)" == "true" ]]; }
kula_answers() { curl --silent --fail --max-time 2 "$KULA_LOCAL_URL" >/dev/null 2>&1; }

[[ "${EUID}" -eq 0 ]] || error "Please run with sudo: sudo bash $0"
for cmd in docker caddy curl grep sed cp install getent; do
  command -v "$cmd" >/dev/null 2>&1 || error "Required command missing: $cmd"
done
docker compose version >/dev/null 2>&1 || error "Docker Compose plugin not installed."
[[ -f "${CADDYFILE}" ]] || error "Caddyfile not found at ${CADDYFILE}. Set CADDYFILE=/your/path for a non-standard installation."

# Default is the newest published image; pin a release (or roll back) with:
# sudo KULA_VERSION=x.y.z bash deploy/setup.sh
KULA_VERSION="${KULA_VERSION:-latest}"
[[ "$KULA_VERSION" =~ ^([0-9]+\.[0-9]+\.[0-9]+|latest)$ ]] \
  || error "Invalid KULA_VERSION '${KULA_VERSION}'. Expected x.y.z or latest."
export KULA_VERSION

info "Validating the existing Caddy configuration"
caddy validate --config "$CADDYFILE" --adapter caddyfile >/dev/null \
  || error "Current Caddyfile already fails validation; refusing to modify it."

info "Checking Docker Compose configuration"
compose config --quiet

# Without this, the health check below could be answered by some other process on the port.
if ! container_running && kula_answers; then
  error "Port 27960 is already served by something other than the ${CONTAINER} container (e.g. a native Kula install)."
fi

image_of() { docker inspect -f "{{.Config.Image}} {{.Image}}" "$CONTAINER" 2>/dev/null || true; }
PREVIOUS_IMAGE="$(image_of)"
info "Pulling and starting c0m4r/kula:${KULA_VERSION} (persistent volume remains intact)"
compose pull
compose up -d

info "Waiting for the localhost health endpoint"
ready=false
for _ in {1..30}; do
  if container_running && kula_answers; then
    ready=true
    break
  fi
  sleep 1
done
if [[ "$ready" != "true" ]]; then
  compose logs --tail=35 kula >&2 || true
  error "Kula is not healthy at 127.0.0.1:27960; Caddy was not changed."
fi

if [[ -e "$SITEFILE" ]]; then
  # Treat any existing snippet as operator-owned; never silently rewrite credentials.
  grep -Fq '# Managed by kula-monitor-stack setup.sh' "$SITEFILE" \
    || error "${SITEFILE} already exists but was not generated by this project. Check it manually."
  grep -Fxq "$IMPORT_LINE" "$CADDYFILE" \
    || error "Existing Kula Caddy snippet found but its import is absent. Please inspect ${CADDYFILE}; refusing to auto-repair."
  DOMAIN="$(sed -n 's/^\([A-Za-z0-9.-]*\) {$/\1/p' "$SITEFILE" | head -1)"
  info "Existing Caddy configuration retained. No password or domain changes."
else
  info "First-time Caddy setup (one-time interactive step)"
  read -r -p "Subdomain (e.g. monitor.example.com): " DOMAIN || error "Input aborted."
  DOMAIN="${DOMAIN,,}"
  [[ "$DOMAIN" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}$ ]] \
    || error "Invalid domain. Provide a normal fully qualified domain name."
  # Avoid accidentally defining a site that is already configured. The adapted JSON
  # includes every imported file and matches exact host names only.
  ADAPTED="$(caddy adapt --config "$CADDYFILE" --adapter caddyfile 2>/dev/null)" \
    || error "Could not adapt ${CADDYFILE} to check for existing sites."
  if grep -Fq "\"${DOMAIN}\"" <<<"$ADAPTED"; then
    error "Domain ${DOMAIN} is already configured in Caddy; check existing routes first."
  fi
  read -r -p "Dashboard username [kula]: " USERNAME || error "Input aborted."
  USERNAME="${USERNAME:-kula}"
  [[ "$USERNAME" =~ ^[A-Za-z][A-Za-z0-9_-]{0,31}$ ]] \
    || error "Username may contain only letters, digits, dash and underscore."
  read -r -s -p "Dashboard password (min. 12 characters): " PASSWORD || error "Input aborted."
  printf '\n'
  [[ ${#PASSWORD} -ge 12 ]] || error "Please choose a longer password (at least 12 characters)."
  read -r -s -p "Repeat password: " PASSWORD_CONFIRM || error "Input aborted."
  printf '\n'
  [[ "$PASSWORD" == "$PASSWORD_CONFIRM" ]] || error "Passwords do not match."
  unset PASSWORD_CONFIRM
  # No --plaintext flag: keep the password out of the process argument list.
  HASH="$(printf '%s\n' "$PASSWORD" | caddy hash-password --algorithm bcrypt)" \
    || error "Could not hash the dashboard password."
  unset PASSWORD
  [[ -n "$HASH" ]] || error "Caddy returned an empty password hash."

  # basic_auth was added in Caddy 2.8; older releases only know the old name.
  AUTH_DIRECTIVE="basic_auth"
  if [[ "$(caddy version 2>/dev/null)" =~ ^v?2\.[0-7]\. ]]; then
    AUTH_DIRECTIVE="basicauth"
  fi

  # From here on, any failure or Ctrl-C restores the previous Caddy state.
  BACKUP=""
  RELOAD_ATTEMPTED=false
  rollback_caddy() {
    if [[ -n "$BACKUP" ]]; then
      cp -p "$BACKUP" "$CADDYFILE"
    fi
    rm -f "$SITEFILE"
    if [[ "$RELOAD_ATTEMPTED" == "true" ]]; then
      caddy reload --config "$CADDYFILE" --adapter caddyfile >/dev/null 2>&1 || true
    fi
    printf 'Caddy changes rolled back%s.\n' "${BACKUP:+ (backup: ${BACKUP})}" >&2
  }
  trap 'rollback_caddy' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM

  # Write the protected site config before importing it. Site file contains only a hash;
  # restrict it to the caddy group of the official packages, else keep it world-readable
  # so an unknown service user can still read it on the next Caddy restart.
  if getent group caddy >/dev/null 2>&1; then
    install -m 0640 -o root -g caddy /dev/null "$SITEFILE"
  else
    install -m 0644 /dev/null "$SITEFILE"
  fi
  cat > "$SITEFILE" <<CADDY
# Managed by kula-monitor-stack setup.sh (do not commit this file to Git)
${DOMAIN} {
    encode zstd gzip
    ${AUTH_DIRECTIVE} {
        ${USERNAME} ${HASH}
    }
    reverse_proxy 127.0.0.1:27960
}
CADDY

  BACKUP="${CADDYFILE}.kula-backup-$(date +%Y%m%d-%H%M%S)"
  cp -p "$CADDYFILE" "$BACKUP"
  # Append an explicit import; leave all existing site blocks untouched.
  printf '\n# Kula monitoring site\n%s\n' "$IMPORT_LINE" >> "$CADDYFILE"
  info "Validating modified Caddyfile before reload"
  caddy validate --config "$CADDYFILE" --adapter caddyfile \
    || error "Caddy validation failed."
  RELOAD_ATTEMPTED=true
  caddy reload --config "$CADDYFILE" --adapter caddyfile \
    || error "Caddy reload failed."
  trap - EXIT INT TERM
  info "Caddy configuration installed. Backup: ${BACKUP}"
fi

# Compare image IDs as well, so an updated "latest" is reported too.
CURRENT_IMAGE="$(image_of)"
if [[ -z "$PREVIOUS_IMAGE" ]]; then
  printf '\nKula image: %s (new installation)\n' "${CURRENT_IMAGE%% *}"
elif [[ "$PREVIOUS_IMAGE" != "$CURRENT_IMAGE" ]]; then
  printf '\nKula image: %s (was %s)\n' "${CURRENT_IMAGE%% *}" "${PREVIOUS_IMAGE%% *}"
else
  printf '\nKula image: %s (unchanged)\n' "${CURRENT_IMAGE%% *}"
fi
printf 'Kula health: %s\n' "$KULA_LOCAL_URL"
printf 'Dashboard: https://%s\n' "${DOMAIN:-<see $SITEFILE>}"
printf 'History volume: kula-monitor-data (preserved across updates)\n'
printf 'To update: git pull && sudo bash %s/setup.sh\n' "$ROOT_DIR"
printf 'To inspect history: docker exec %s /app/kula inspect\n' "$CONTAINER"
printf 'Logs: docker logs -f %s\n' "$CONTAINER"
printf '\nReminder: Point the subdomain DNS record to this server and allow ports 80/443 for Caddy HTTPS.\n'
